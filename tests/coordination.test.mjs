  const auth = { token: hub.act(owner, "invite.create", { workspaceId: w.id }).token, secret: randomBytes(32).toString("hex"), name: "离线执行者" };
  const client = new HubClient(); t.after(() => client.close());
  await client.connect(`ws://127.0.0.1:${hub.port}`, auth);
  const lane = await client.call("lane.create", { sessionId: s.id, provider: "codex" });
  const ap = await client.call("run.request", { sessionId: s.id, laneId: lane.id, mode: "read-only", prompt: "检查" });
  hub.act(owner, "approval.decide", { id: ap.id, allow: true });
