const commitA = "a".repeat(40), commitB = "b".repeat(40);
async function setup(t) {
  const dir = await mkdtemp(join(tmpdir(), "rpo-coordination-"));
  const hub = new Hub(dir);
  const owner = { id: "owner", name: "房主", host: true };
  const w = hub.act(owner, "workspace.create", { name: "协作", branch: "main" });
  const peers = {};
  for (const role of ["viewer", "commenter", "editor", "owner"]) {
    const p = { id: role + "-guest", name: role, host: false, workspaceId: w.id };
    hub.registerMember(p, w.id, role); peers[role] = p;
  }
  const s = hub.act(owner, "session.create", { workspaceId: w.id, title: "认证页面" });
  const act = (peer, method, args = {}) => hub.act(peer, method, { workspaceId: w.id, sessionId: s.id, ...args });
  const lane = act(peers.editor, "lane.create", { provider: "codex" });
  t.after(async () => { await hub.close(); await rm(dir, { recursive: true, force: true }); });
  return { hub, owner, w, s, peers, act, lane, dir };
}
