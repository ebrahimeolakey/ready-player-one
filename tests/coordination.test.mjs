  const event = { sessionId: s.id, laneId: lane.id, runId: ap.id, eventId: "durable-event", role: "assistant", text: "已读取" };
  await client.call("run.entry", event);
  const disconnected = new Promise((resolve, reject) => {
    const timer = setTimeout(() => { hub.off("change", changed); reject(Error("disconnect not observed")); }, 2000);
    const changed = () => { if (hub.db.sessions[0].lanes.at(-1).offlineSince) { clearTimeout(timer); hub.off("change", changed); resolve(); } };
    hub.on("change", changed);
  });
  client.close(); await disconnected;
  const stored = hub.db.sessions[0].lanes.at(-1);
  assert.equal(stored.status, "running"); assert.equal(stored.activeRunId, ap.id);
  await client.connect(`ws://127.0.0.1:${hub.port}`, auth);
  const reconciliation = await client.call("run.reconcile", { sessionId: s.id, laneId: lane.id, runId: ap.id });
  assert.deepEqual(reconciliation.acceptedEventIds, ["durable-event"]);
  assert.equal((await client.call("run.entry", event)).duplicate, true);
  await client.call("run.finish", { sessionId: s.id, laneId: lane.id, runId: ap.id, status: "done" });
  assert.equal(stored.entries.filter(e => e.text === "已读取").length, 1);
  assert.equal(stored.status, "done");
